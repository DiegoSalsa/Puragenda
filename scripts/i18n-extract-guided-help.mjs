import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import ts from "typescript";

const root = process.cwd();
const inputs = [
  join(root, "src", "components", "dashboard", "contextual-help.tsx"),
  join(root, "src", "components", "dashboard", "tutorial.tsx"),
];
const catalogFile = join(root, "messages", "legacy", "es.json");
const catalog = JSON.parse(readFileSync(catalogFile, "utf8"));
const sourceToId = {};

function idFor(source) {
  return createHash("sha256").update(source).digest("base64url").slice(0, 12);
}

function looksSpanish(source) {
  return source.length >= 2 && /[A-Za-zÀ-ÿ¿¡]/.test(source)
    && (/[áéíóúñ¿¡]/i.test(source) || /\b(siguiente|anterior|atrás|finalizar|esta|este|aquí|ayuda|sección|pantalla|negocio|cita|citas|cliente|clientes|servicio|servicios|configuración|gestiona|revisa|puedes|desde|para|por|con|sin|nuevo|nueva|ver|menú|área)\b/i.test(source))
    && !/^[#.[\]\w:=* >+~/-]+$/.test(source);
}

for (const file of inputs) {
  const code = readFileSync(file, "utf8");
  const sourceFile = ts.createSourceFile(file, code, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  function visit(node) {
    if ((ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) && looksSpanish(node.text)) {
      const id = idFor(node.text);
      catalog[id] = node.text;
      sourceToId[node.text] = id;
    }
    ts.forEachChild(node, visit);
  }
  visit(sourceFile);
}

writeFileSync(catalogFile, JSON.stringify(Object.fromEntries(Object.entries(catalog).sort((a, b) => a[0].localeCompare(b[0]))), null, 2) + "\n", "utf8");
const generated = `// Generated by scripts/i18n-extract-guided-help.mjs.\nexport const GUIDED_HELP_KEYS: Readonly<Record<string, string>> = ${JSON.stringify(sourceToId, null, 2)};\n`;
writeFileSync(join(root, "src", "i18n", "guided-help-keys.ts"), generated, "utf8");
process.stdout.write(`Guided help messages: ${Object.keys(sourceToId).length}\n`);
